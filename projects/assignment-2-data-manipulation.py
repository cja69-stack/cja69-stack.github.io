import requests
import sqlite3
import os
api_key = os.environ["NEWS_API_KEY"]
topic = input("Enter a topic: ")
url = f"https://newsapi.org/v2/everything?q={topic}&apiKey={api_key}"
response = requests.get(url)
data = response.json()
articles = data["articles"][:5]

db = sqlite3.connect("news.db")
cursor = db.cursor()

# Drop old table structure if it exists to apply the new schema
cursor.execute("DROP TABLE IF EXISTS news")
cursor.execute("CREATE TABLE IF NOT EXISTS news (title TEXT, description TEXT, date TEXT)")

for article in articles:
  title = article["title"]
  description = article["description"]
  date = article["publishedAt"][:10]

  cursor.execute(
      "INSERT INTO news (title, description, date) VALUES (?, ?, ?)",
      (title, description, date)
  )

  db.commit()

  cursor.execute("SELECT * FROM news")
  results = cursor.fetchall()

  print("\nTop Headlines:")

  for i, article in enumerate(results, 1):
    print(f"{i}. Title: {article[0]}")
    print(f"   Description: {article[1]}")
    print(f"   Date: {article[2]}")
    print("\nData has been saved to the database")